# คำถามที่พบบ่อย ใช้เป็นเพียงตัวช่วยตรวจคำลงท้าย
# ไม่สามารถจำแนกประโยคคำถามภาษาไทยได้อย่างสมบูรณ์
_Q_WORDS = (
    r"(?:ไหม|อะไร|หรือเปล่า|หรือยัง|หรือไม่|ใคร|ที่ไหน|ไหน|"
    r"เท่าไร|เท่าไหร่|กี่[^\s]{0,4}|อย่างไร|ยังไง|"
    r"เมื่อไร|เมื่อไหร่|ทำไม)"
)


def femme(text):
    """
    แก้คำลงท้าย 'ครับ' ในข้อความทั่วไป
    เป็นเพียง post-processing ขั้นพื้นฐาน ไม่ใช่ตัวจำแนกประโยค
    ควรใช้กับข้อความคำตอบของผู้ช่วย ไม่ใช่ข้อความอ้างอิงหรือโค้ด
    """
    if not text:
        return text

    # แก้คำลงท้ายที่มีรูปแบบคำถามชัดเจน
    text = re.sub(
        rf"({_Q_WORDS})([^\s]{{0,8}})ครับ(?=$|[\s.!?…])",
        r"\1\2คะ",
        text,
    )

    # แก้คำลงท้ายสุภาพทั่วไป
    text = re.sub(
        r"นะครับ(?=$|[\s.!?…])",
        "นะคะ",
        text,
    )
    text = re.sub(
        r"ครับ(?=$|[\s.!?…])",
        "ค่ะ",
        text,
    )

    return text
