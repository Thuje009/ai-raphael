# คำที่บ่งบอกว่าเป็นประโยคคำถาม (ใช้เลือก "คะ" แทน "ค่ะ")
_Q_WORDS = r"(?:ไหม|อะไร|หรือเปล่า|หรือยัง|หรือไม่|ใคร|ที่ไหน|ไหน|เท่าไร|เท่าไหร่|กี่[^\s]{0,4}|อย่างไร|ยังไง|เมื่อไร|เมื่อไหร่|ทำไม)"


def femme(text):
    """แปลงคำลงท้ายของข้อความที่พูดเป็นเสียงผู้หญิง (ครับ -> ค่ะ/คะ) ใช้เป็นตาข่ายนิรภัยกับทุกประโยคที่พูดออกไป"""
    if not text:
        return text
    text = text.replace("นะครับ", "นะคะ")
    text = re.sub(rf"({_Q_WORDS})([^\s]{{0,8}})ครับ", r"\1\2คะ", text)
    return text.replace("ครับ", "ค่ะ")